import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {validateCatalogs,createTranslator} from '../app/i18n.mjs';
import {catalogs as fallback} from '../browser-extension/locale-catalogs.js';

// Run after Root merges LOCALE-ADDITIONS and Claude supplies English. No store package.
export function packageChromeLocales(root){
 const tables={};
 for(const language of ['zh','en']){
  const source=JSON.parse(fs.readFileSync(path.join(root,'locales',language+'.json'),'utf8'));
  tables[language]=Object.fromEntries(Object.keys(fallback.zh).map(key=>[key,source[key]??fallback[language][key]]));
 }
 validateCatalogs(tables);const translate=createTranslator(tables);
 const target=path.join(root,'browser-extension');
 fs.writeFileSync(path.join(target,'locale-catalogs.js'),'// Generated by scripts/package-chrome-locales.mjs. Flat semantic catalogs.\nexport const catalogs = '+JSON.stringify(tables,null,2)+';\n');
 for(const language of ['zh','en']){
  const folder=path.join(target,'_locales',language==='zh'?'zh_CN':language);fs.mkdirSync(folder,{recursive:true});
  const messages=Object.fromEntries([['helperName','chrome.helperName'],['helperDescription','chrome.helperDescription']].map(([name,key])=>[name,{message:translate(key,{},language)}]));
  fs.writeFileSync(path.join(folder,'messages.json'),JSON.stringify(messages,null,2)+'\n');
 }
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))packageChromeLocales(path.resolve(process.argv[2]||fileURLToPath(new URL('..',import.meta.url))));
